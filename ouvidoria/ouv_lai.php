			<p><strong>Seguem as Informações conforme Decreto nº 27.073/24</strong></p>
			
			<p>Art. 23. O recurso é cabível no prazo de 10 (dez) dias a contar da data do recebimento da resposta, nas seguintes hipóteses: <br><br>
				I - negativa parcial ou total de acesso à informação; <br>

				II - ausência de justificativa legal para recusa de acesso; <br>

				III - informação incorreta, incompreensível, incompleta ou insatisfatória; <br><br>

				§ 1º Em primeira instância, o recurso de que trata o caput deverá ser dirigido à autoridade máxima da Unidade Gestora que adotou a decisão, ou a um responsável por ela designado, que deverá apreciá-lo no prazo de (05) cinco dias, a contar da data de seu recebimento.<br><br>

				§ 2º No caso de pedidos de informações direcionados à Controladoria-Geral do Município, por meio da Ouvidoria-Geral do Município, o recurso de primeira instância será direcionado à Chefia do Departamento de Transparência e Acesso à Informação, que responderá após consulta à Subcontroladoria-Geral responsável pelo tema.<br><br>

				§ 3º Desprovido o recurso, o requerente poderá reapresentá-lo em segunda instância, no prazo de 10 (dez) dias, a contar da data de ciência da decisão, devendo dirigi-lo ao Controlador-Geral do Município ou a quem por ele seja delegada essa competência, que se manifestará no prazo de 05 (cinco) dias, a contar da data de seu recebimento.<br><br>

				Art. 24. O solicitante pode protocolar as seguintes demandas por meio de registro na mesma plataforma eletrônica utilizada para o pedido inicial:<br><br>

				I - recurso para negativa de acesso à informação, dentro dos prazos estabelecidos neste Decreto;<br>

				II - reclamação pela ausência de resposta da administração;<br>

				III - pedido de desclassificação de informação classificada, por meio da ferramenta de Solicitação à Ouvidoria;<br><br>

				§ 1º O requerente que deseje protocolizar uma das demandas descritas no caput deverá respeitar o decurso do prazo de resposta à demanda inicial, antes de protocolizá-la à autoridade correspondente.<br><br>

				§ 2º O recurso para negativa de acesso à informação deverá ser encaminhado, por meio da ferramenta própria existente no ambiente de recursos da plataforma eletrônica do Sistema Municipal de Ouvidoria, conforme instâncias recursais, às autoridades descritas nos §§ 1º ao 3º do art. 22 deste Decreto.<br><br>

				§ 3º O pedido de desclassificação da informação deverá ser encaminhado à plataforma da Ouvidoria-Geral, que encaminhará à Controladoria-Geral do Município ou ao agente público designado, que deverá manifestar-se no prazo de 30 (trinta) dias, contados do recebimento do pedido.<br><br>

				§ 4º A reclamação pela ausência de resposta no prazo devido deverá ser registrada no ambiente de recursos da plataforma eletrônica do SisOuv, no prazo de 10 (dez) dias contados do término do prazo para resposta.<br><br>

				§ 5º Caso haja protocolização cumulativa de demandas idênticas em uma ou mais ouvidorias, é facultado ao agente público dar prosseguimento somente ao primeiro pedido, registrando-se este procedimento e o número do primeiro protocolo nos pedidos seguintes, como justificativa para seu encerramento.
