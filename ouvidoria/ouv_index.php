            <p style="font-size: 15px;">&nbsp;</p>
            <p style="font-size: 15px;">&nbsp;</p>
            <p style="font-size: 15px;">&nbsp;</p>
            <p style="font-size: 15px;">&nbsp;</p>
            <p style="font-size: 15px;">A Lei n. 13.460/2017 estabelece que o prazo de resposta a essas manifestações do cidadão é de até 30 dias, prorrogáveis por mais 30, somente se houver justificativa expressa. Já os Pedidos de Acesso à Informação (Lei n. 12.527/2011) têm prazo de resposta de 20 dias, prorrogáveis por mais 10, também sob justificativa.</p>
            <p style="font-size: 15px;">A partir das informações trazidas pelos cidadãos, a Ouvidoria pode identificar melhorias, propor mudanças, assim como apontar situações irregulares.&nbsp;Por exemplo, ao receber uma sugestão, a ouvidoria deve dar uma resposta, dizendo se a ideia será implantada. Para isso, faz uma análise inicial, entra em contato com a área responsável e responde, explicando o que será feito, ou justificando porque a sugestão não poderá ser aproveitada.&nbsp;</p>
            <p style="font-size: 15px;">Clique no botão abaixo conforme o tipo de manifestação desejada. <strong>Participe! Divulgue a Ouvidoria!</strong></p>
