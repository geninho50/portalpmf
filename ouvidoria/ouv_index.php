                        <td style="border: none; font-size: 15px; vertical-align: middle;">A <strong>Ouvidoria</strong> <strong>Municipal</strong> é um espaço de participação e  controle social, aberto para a sociedade.&nbsp;Através de canais de  atendimento presenciais e eletrônicos, recebe e responde manifestações  como <strong>sugestões</strong>, <strong>elogios</strong>, <strong>solicitações</strong>, <strong>reclamações</strong> e <strong>denúncias</strong> sobre políticas e serviços&nbsp;públicos. <br></td>
                        <td style="border: none; font-size: 15px; vertical-align: middle;"><a href="https://falabr.cgu.gov.br/web/SC/Florian%C3%B3polis"><img style="border: none;" width="80%" heigth="80%" src="http://www.pmf.sc.gov.br/images/falabr-logo-azul.png" alt=""></a></td>
