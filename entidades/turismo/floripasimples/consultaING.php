						<h2>PUBLIC CONSULTATION 2018: </h2>

						<p>In 2016 was held the first formal public consultation that included, in addition to the Beira Mar Park and Marina Project, also the studies resulting from the PMI (Proceedings of Manifestation of Interest), Bidding Notice and its annexes. After that, all documents were analyzed by the Court of Accounts of the State of Santa Catarina (SC TCE) that recommended some modification that changed both Bidding Notice and the documents attached to it. <br /><br>
						Therefore, at this moment the Florianopolis City Hall launch the public consultation of the Bidding Notice, Term of Reference and Contract updated versions, seeking inputs from society and companies interested in the documents presented. Annexes of Bidding Notice approved in the previous stage, as PMI studies, which will serve as a basis for the proposals for the bidding process are also presented for reference. <br />
						<br>
						This public consultation will be open for 90 days, from 2018/12/19 to 2019/03/18.   After this stage, the documents will be complemented with suggestions and sent for further analysis of the TCE-SC.  Once TCE have provide the advice, the concession bidding will be launched.</p><br>

