						<h2>Consulta Pública 2018: </h2>

						<p>Após a consulta pública realizada no ano de 2016 que compreendia, além do Projeto urbanístico do Parque e Marina Beira Mar, também os estudos resultado do PMI  (Procedimento de Manifestação de Interesse), Edital e seus anexos o Projeto do Parque Urbano e Marina Beira Mar foi analisado pelo Tribunal de Contas do Estado de Santa Catarina (TCE SC)que recomendou algumas alterações na proposta de edital. Estas alterações geraram impactos tanto no próprio edital como nos documentos anexos a este. <br />
						Sendo assim, nesse momento a Prefeitura Municipal de Florianópolis coloca em Consulta Pública a versão atualizada do Edital, Termo de Referência e Minuta de Contrato para buscar considerações da sociedade e empresas interessadas em relação aos documentos apresentados. São apresentados como simples referência também os Anexos ao Edital aprovados na etapa anterior e que servirão como base para elaboração das propostas da futura licitação. <br />
						Esta consulta ficará aberta ao público para busca de considerações pelo prazo de 90 dias, de 19/12/2018 até 18/03/2019. Após esta etapa os documentos em análise serão complementados e encaminhados para nova análise do TCE-SC e com o retorno desta análise serão encaminhadas para licitação de concessão.  </p><br>

