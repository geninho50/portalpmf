		    <h5 class="bold">TERMO DE RESPONSABILIDADE DE INFORMAÇÃO</h5>
			    
		    <div id="corpo">
			    <p>Eu, ____________________________________, declaro ter recebido, nesta data, as informações de propriedade da Prefeitura Municipal de Florianópolis, comprometendo-me, no que couber, a:</p>
				<p class="">1.	Acessar o Sistema de Informações, incluindo a infraestrutura de tecnologia da informação somente por necessidade de serviço, realizando as tarefas e operações, em estrita observância 
				   aos procedimentos, normas e disposições contidas na instrução normativa que rege os acessos a estes ativos de tecnologia da informação; </p>
				<p>2.	Não revelar fora do âmbito profissional fato ou informação de qualquer natureza de que tenha conhecimento por força de minhas atribuições, salvo em decorrência de decisão competente 
				   na esfera legal ou judicial, bem como de autoridade superior; </p>
				<p>3.	Manter a necessária cautela quando da exibição de dados em tela, impressora ou na gravação em meios eletrônicos, a fim de evitar que deles venham a tomar ciência pessoas não autorizadas;</p>
				<p>4.	Não me ausentar da estação de trabalho sem encerrar a sessão de uso do sistema, garantindo assim a impossibilidade de acesso indevido por terceiros;</p>
				<p>5.	Não revelar minha senha de acesso ao(s) sistema(s) a ninguém e tomar o máximo de cuidado para que ela permaneça somente de meu conhecimento;</p>
				<p>6.	Responder, em todas as instâncias, pelas conseqüências das ações ou omissões de minha parte que possam pôr em risco ou comprometer a exclusividade de conhecimento de minha senha ou das 
				   transações a que tenha acesso. </p>
				<p>7.	Incluir situação vacinal e emitir Certificados Internacionais de Vacinação, em estrita observância aos procedimentos, normas e disposições contidas na instrução normativa que rege estas atribuições; </p>
				<p>Declaro, ainda, estar plenamente esclarecido e consciente que:</p>
				<p>1.	É minha responsabilidade cuidar da integridade, confidencialidade e disponibilidade dos dados, informações contidas nos sistemas, e da infraestrutura de tecnologia informação a que tenha acesso, devendo comunicar por escrito à minha Chefia imediata quaisquer indícios ou possibilidades de irregularidades, de desvios ou falhas identificadas nos sistema e na infraestrutura de tecnologia da informação, sendo proibida a exploração de falhas ou vulnerabilidades porventura existentes; </p>
				<p>2.	Constitui descumprimento de normas legais, regulamentares e quebra de sigilo funcional divulgar dados obtidos dos sistemas de informação e na infraestrutura de tecnologia da informação, aos quais tenha acesso, para outros servidores não envolvidos nos trabalhos executados;</p>
				<p>3.	Devo alterar minha senha sempre que obrigatório ou que tenha suposição de descoberta por terceiros, não usando combinações simples que possam ser facilmente descobertas;</p>
				<p>4.	Respeitar as normas de segurança e restrições de sistema impostas pelos sistemas de segurança implantados na Prefeitura Municipal de Florianópolis (tais como privilégio e direitos de acesso);</p>
				<p>5.	Observar e Cumprir as Boas Práticas de Segurança da Informação, e suas diretrizes, bem como este Termo de Responsabilidade.</p>
				<P>Normativa:</P>
				<p>a) LEI Nº 12.737, DE 30 DE NOVEMBRO DE 2012. Ver na íntegra no endereço:<br>
			     http://www.planalto.gov.br/ccivil_03/_ato2011-2014/2012/lei/l12737.htm </p>
				<p>b) Sem prejuízo das responsabilidades penal e civil, e de outras infrações disciplinares, constitui falta de zelo e dedicação às atribuições do cargo e descumprimento de normas legais e regulamentares, 
					não proceder com cuidado na guarda e utilização de senha ou emprestá-la a outro servidor, ainda que habilitado. </p>
				<p>c) Constitui infração funcional e penal revelar fato de que tem ciência em razão do cargo e que deva permanecer em segredo, ou facilitar-lhe a revelação; inserir ou facilitar a inserção de dados falsos, 
					alterar ou excluir indevidamente dados corretos dos sistemas ou bancos de dados da Administração Pública com o fim de obter vantagem indevida para si ou para outrem, ou para causar dano; bem como 
					modificar ou alterar o sistema de informações ou programa de informática, ou configurações da infraestrutura de tecnologia da informação, sem autorização ou sem solicitação de autoridade competente; 
					ficando o infrator sujeito as punições previstas no Código Penal Brasileiro, conforme responsabilização por crime contra a Administração Pública, tipificados no art.325, 313-A e 313B. </p>
				<p>d) Constitui Infração funcional e penal infringir determinação do poder público, destinada a impedir introdução ou propagação de doença contagiosa; falsificar, no todo ou em parte, documento público, 
					ou alterar documento público verdadeiro; omitir, em documento público ou particular, declaração que dele devia constar, ou nele inserir ou fazer inserir declaração falsa ou diversa da que devia ser escrita,
					com o fim de prejudicar direito, criar obrigação ou alterar a verdade sobre fato juridicamente relevante; atestar ou certificar falsamente, em razão de função pública, fato ou circunstância que habilite 
					alguém a obter cargo público, isenção de ônus ou de serviço de caráter público, ou qualquer outra vantagem; bem como falsificar, no todo ou em parte, atestado ou certidão, ou alterar o teor de certidão 
					ou de atestado verdadeiro, para prova de fato ou circunstância que habilite alguém a obter cargo público, isenção de ônus ou de serviço de caráter público, ou qualquer outra vantagem e apropriar-se o 
					funcionário público de dinheiro, valor ou qualquer outro bem móvel, público ou particular, de que tem a posse em razão do cargo, ou desviá-lo, em proveito próprio ou alheio, ficando o infrator sujeito 
					as punições previstas no Código Penal Brasileiro, conforme responsabilização por crime contra a Administração Pública, tipificados nos art. 268, 297, 299, 301 e 312. </p>
				<p>e) As penalidades previstas neste termo se aplicam ao funcionário público, conforme definido no artigo 327 do Código Penal Brasileiro:</p>
				<p>“Art. 327 - Considera-se funcionário público, para os efeitos penais, quem, embora transitoriamente ou sem remuneração, exerce cargo, emprego ou função pública”.</p>
				<p>§ “1º - Equipara-se a funcionário público quem exerce cargo, emprego ou função em entidade paraestatal, e quem trabalha para empresa prestadora de serviço contratada ou conveniada para a execução de atividade típica da Administração Pública.”</p>
				<p>Declaro, nesta data, <b>ter ciência e estar de acordo com os procedimentos acima descritos,</b> comprometendo-me a respeitá-los e cumpri-los plena e integralmente.</p>
