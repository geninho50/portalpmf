        <p><STRONG>DECRETO N.17.910, DE 22 DE AGOSTO DE 2017. INSTITUI O PLANO MUNICIPAL DE GESTÃO INTEGRADA DE RESÍDUOS SÓLIDOS (PMGIRS) </STRONG> DA CIDADE DE FLORIANÓPOLIS PARA O PERÍODO 2018-2021 E DÁ AS DIRETRIZES PARA SUA REVISÃO. O PREFEITO MUNICIPAL DE FLORIANÓPOLIS, no uso de suas atribuições, de acordo com a Lei Federal n. 12.305, de 2010, e Considerando o art. 18 da Lei Federal n. 12.305, de 2010; Considerando o art. 7º da Lei Federal n. 11.445, de 2007; Considerando o art. 9° da Lei Federal n. 12.305, de 2010, DECRETA: Art. 1º Fica criado o Plano Municipal de Gestão Integrada de Resíduos Sólidos (PMGIRS) da Cidade de Florianópolis para o período 2018-2021 e as diretrizes para sua revisão, atendendo às diretrizes da legislação federal pertinente, visando preparar o Município para os novos processos de gestão dos resíduos sólidos gerados em todas as atividades produtivas em seu território, conforme os Anexos do PMGIRS, parte integrante deste Decreto. Parágrafo único. A atualização do PMGIRS deverá ocorrer em até quatro anos a partir da publicação deste Decreto, ou a qualquer momento que for de interesse do poder público municipal. Art. 2º Este Decreto não altera o sistema de taxa de coleta de lixo ou qualquer tributo municipal referente ao manejo de resíduos sólidos vigente no Município. Art. 3º Este Decreto entra em vigor na data de sua publicação. Florianópolis, aos 22 de agosto de 2017. <Strong>GEAN MARQUES LOUREIRO PREFEITO MUNICIPAL FILIPE MELLO SECRETÁRIO MUNICIPAL DA CASA CIVIL.</Strong></p>
