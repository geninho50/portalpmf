<h1><Strong>1º Semana Floripa Empreendedora</Strong></h1>
<br>
<p>1º Semana Floripa Empreendedora, que tem base legal na LEI 10313/2017, de 21 de novembro de 2017 que institui o Dia Municipal do Empreendedorismo.</p>
 
<br>
<p>A 1º Semana Floripa Empreendedora, tem objetivo de celebrar o Dia Municipal do Empreendedorismo, e através de uma agenda de atividades poder oferecer ao empreendedor de Florianópolis, atendimento, orientação e sobre os processos e programas da Prefeitura e acesso a Crédito do Programa Juro Zero Floripa.</p>


<br>
<br>
<h3>Programação:</h3>
<br>
<p><strong>Participe da Primeira Semana Floripa Empreendedora de 19 a 23 de novembro de 2018.</strong></p>

<br>
<br>
<h3><strong>19 e 20/11 – 10h- 17h - Edição Projeto Floripa Empreendedora no Bairro</strong></h3>
<p><strong>O Evento:</strong> O Projeto Floripa Empreendedora no Bairro tem intuito de incentivar o empreendedorismo local com informações relevantes sobre benefícios e deveres dos empreendedores formalizados, sejam Microempreendedores Individuais (MEIs) ou Micro e Pequenos Empresários (MPEs), melhorando assim o desenvolvimento econômico do município. E oferecerá nos dias 19 e 20 de Novembro orientação de como abrir uma empresa, informações sobre crédito, e vários benefícios para melhor gestão de seu negócio.</p>
<p><strong>Público alvo:</strong> Empresários, Empreendedores e comunidade em geral.</p>
<p><strong>Local:</strong> Catedral Metropolitana de Florianópolis, SC</p>
<p><strong>Realização:</strong> Prefeitura de Florianópolis - Apoio:  Sebrae, Banco do Empreendedor e Entidades Empresárias;</p>

