        <p><STRONG>O Plano Municipal de Gestão Integrada de Resíduos Sólidos de Florianópolis - PMGIRS </STRONG> foi instituído pelo decreto municipal nº 17.910 em 22 de agosto de 2017, após ter sido elaborado por técnicos da Secretaria Municipal de Infraestrutura e da COMCAP, com o apoio e coordenação de uma consultoria especializada na implementação de planos municipais e na gestão de resíduos sólidos urbanos. O PMGIRS passa a compor e atualizar o Plano Municipal Integrado de Saneamento Básico (PMISB), complementando-o no que se refere à limpeza urbana e manejo de resíduos sólidos. O diagnóstico, prognóstico e demais estudos tiveram como base documentos, levantamentos e eventos (conferências, audiências públicas e oficinas comunitárias) realizados no município,  que constam do PMISB e do Plano Municipal de Coleta Seletiva (PMCS). Além disso, faz menção tanto aos sistemas de manejo de resíduos sólidos em operação quanto aos que foram recentemente desativados.</p>
        <p>Com os novos marcos regulatórios que estabelecem a Política Nacional de Saneamento Básico (PNSB) e a Política Nacional de Resíduos Sólidos (PNRS), o município passou a ter obrigações e metas na gestão dos resíduos sólidos definidas por planos nacionais, estaduais e municipais de saneamento básico e de resíduos sólidos - inclusive como condição para ter acesso a recursos da União que são disponibilizados por meio de editais públicos. E a principal determinação da PNRS é a de que não deverão mais ser enviados ao aterro sanitário resíduos sólidos recicláveis, tanto a fração orgânica como a seca.</p>   
        <p>Assim, o modelo de gestão de resíduos sólidos atualmente adotado no município deve se adequar à legislação, privilegiando a não geração, a minimização da geração e o manejo diferenciado dos resíduos sólidos, com a triagem, a compostagem e a recuperação dos resíduos que constituem bem econômico e valor social, e a disposição final exclusivamente dos rejeitos, de forma ambientalmente adequada. E, para os próximos 10 anos, o cenário do manejo dos resíduos sólidos urbanos deverá se adequar através de planejamento específico que vise aumentar os índices de reciclagem e compostagem atuais, objetivando o atendimento das metas. </p>
        <p>Neste sentido, o município, que já previu algumas ações no Plano Municipal Integrado de Saneamento Básico e no Plano Municipal de Coleta Seletiva, agora define programas, metas e ações através do Plano Municipal de Gestão Integrada de Resíduos Sólidos de Florianópolis para o período 2018-2021, os quais são apresentados em forma de cadernos, com destaque para o de nº 05 e seus anexos. Este caderno nº 05 é resultante de um diagnóstico, um prognóstico, dos aspectos gerais do planejamento das ações, de minutas de projetos de lei e dos produtos do Plano Municipal de Coleta Seletiva.</p>
