									<p><b>- Capacitação:</b> Essa atividade é realizada por demanda de grupos interessados, principalmente, em oficinas de mudas.</p> 

									<p><b>•	Função:</b> Atualmente, o viveiro está sendo remodelado com o objetivo de produzir mudas de espécies nativas frutíferas, hortaliças, PANCs e plantas medicinais. A intenção é ampliar a distribuição das mudas aos Centros de Saúde, Unidades de Ensino e Hortas Comunitárias, em parceria com o Projeto Municipal “Cultiva Floripa”. </p>   

