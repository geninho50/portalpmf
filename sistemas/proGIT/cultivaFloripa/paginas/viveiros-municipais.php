									<p><b>- Área de produção:</b> Área onde são feitas as mudas. A área dispõe de um espaço para armazenar o composto, uma peneira elétrica para peneirar o mesmo, estantes para armazenar os materiais utilizados diariamente, bancada onde é efetuado o beneficiamento das sementes e outros procedimentos relacionados à produção e a manutenção das mudas.</p>

									<p><b>- Canteiros de matrizes:</b> Uma área composta por 40 canteiros. Atualmente, alguns destes canteiros estão sendo utilizados para o armazenamento de mudas.</p>

									<p><b>- Área de aclimatação:</b> Composta por 17 canteiros, protegidos por telas de sombrite.</p>

									<p><b>- Área de expansão:</b> Onde se encontram mesas para exposição das mudas ao sol, um quiosque onde são armazenadas as ferramentas e uma caixa d’água com captação de água de chuva de 15.000 l.</p>
									
									<p><b>•	Atividades:</b> No viveiro acontecem diariamente as seguintes atividades:</p>
									
