<h1>CONSULTA PÚBLICA - ENCERRADA EM 28 de FEVEREIRO</h1>
<p> A Prefeitura de Florianópolis e o Departamento de Engenharia Sanitária e Ambiental da Universidade Federal de Santa Catarina (UFSC) disponibilizam pela internet, até o dia 28 de fevereiro, consulta pública para complementar as informações que foram levantadas junto aos participantes das oficinas comunitárias de diagnóstico e planejamento da drenagem urbana, realizadas entre os meses de agosto e dezembro. A ideia é levar mais cidadãos a contribuírem com a identificação dos problemas relativos à drenagem urbana em nível local, bem como a apresentarem sugestões e propostas.</p>
<p>A participação popular na consulta será através do formulário eletrônico que pode ser acessado pelo link abaixo: </p><br />


<p>As oficinas e a consulta pública visam embasar a construção do Plano Diretor de Drenagem e Manejo de Águas Pluviais para Florianópolis e se configuram como a primeira etapa do processo.</p>
</div>

<div class="containers">
<h1>OFICINAS PARA DIAGNÓSTICO DA DRENAGEM URBANA NO MUNICÍPIO</h1>
<p>A Prefeitura de Florianópolis e o Departamento de Engenharia Sanitária e Ambiental da Universidade Federal de Santa Catarina (UFSC) realizaram entre agosto e dezembro uma série de 15 oficinas de diagnóstico e planejamento em todo o município de Florianópolis.</p>
<p> O objetivo foi de identificar os problemas como alagamentos e inundações em nível local e discutir soluções para a drenagem urbana.</p>
<p>As oficinas foram realizadas conforme cronograma abaixo e tiveram o patrocínio da Caixa Econômica Federal e apoio dos Conselho Municipal e Conselhos Locais de Saúde como facilitadores.</p>
</div>

<div class="containers">
<h1>COMISSÃO ORGANIZADORA</h1>
<p>Técnicos da Prefeitura e professores do Departamento de Engenharia Sanitária e Ambiental da UFSC participam da Comissão Especial de Estudos de Drenagem e Manejo de Águas Pluviais de Florianópolis (DREMAP) criada pelo Decreto Municipal 14942/2015 durante a 1ª Conferência Municipal de Saneamento Básico. A Comissão tem como principal objetivo subsidiar a elaboração do Plano Diretor de Drenagem e Manejo das Águas Pluviais Urbanas de Florianópolis.</p>
</div>
